import fs from "node:fs";
import { performance } from "node:perf_hooks";
import { applyRecode, computeVariable } from "../../src/utils/dataPrep";
import { ensureDatasetMetadata } from "../../src/utils/metadata";
import { getAnalysisRows, computeProfile, parseCSV } from "../../src/utils/stats";
import { computeReliability } from "../../src/utils/reliability";
import { createFactorSample } from "../../src/utils/factorSample";
import { computeFactorPca } from "../../src/utils/factorPca";
import { aggregateData } from "../../src/utils/aggregation";
import { useDataStore } from "../../src/stores/useDataStore";

const [source, out] = process.argv.slice(2);
const rows = parseCSV(fs.readFileSync(source, "utf8").replace(/^\uFEFF/, ""));
const cols = rows[0];
const orig = ensureDatasetMetadata({id:"demo",name:"khao-sat",rows:rows.length-1,columns:cols.length,columnNames:cols,data:rows,preview:rows,sourceFormat:"csv",createdAt:"2026-11-12",updatedAt:"2026-11-12"});
const ts = ["TS1","TS2","TS3","TS4","TS5"];
const nt = ["NT1","NT2","NT3","NT4","NT5"];
const items = [...ts,...nt];
for (const col of items) orig.variables![col] = {...orig.variables![col], measure:"ordinal", decimals:0};
orig.variables!.TS4 = {...orig.variables!.TS4, missingValues:["7"]};
const masked = getAnalysisRows(orig);
const a = computeReliability(masked, ts);
const b = computeReliability(masked, nt);
const pca = computeFactorPca(createFactorSample(masked, items), 2);
const cc = [masked[0], ...masked.slice(1).filter(r => items.every(col => r[cols.indexOf(col)] !== ""))];
const yearCol = "nam_hoc";
const groups = [...new Set(cc.slice(1).map(r=>r[cols.indexOf(yearCol)]))];
const group = applyRecode(cc, {sourceCol:yearCol,rules:groups.sort().map((from,i)=>({type:"value",from,to:String(i+1)})),targetMode:"different",targetCol:"NAM_HOC_MA"});
if (group.error) throw Error(group.error);
const x = computeVariable(group.rows, "DIEM_TS", "MEAN([TS1], [TS2], [TS3], [TS4], [TS5])").rows;
const scored = computeVariable(x, "DIEM_NT", "MEAN([NT1], [NT2], [NT3], [NT4], [NT5])").rows;
const agg = aggregateData(scored, {groupByCols:["nam_hoc"],measureCol:"DIEM_TS",func:"mean"});
const st=useDataStore.getState();
st.setDatasets([orig]);
st.setSelectedDatasetId("demo");
const j=cols.indexOf("TS1");
const before=useDataStore.getState().datasets[0].data![1][j];
st.updateCell(0,j,before==="5" ? "4" : "5","demo");
const changed=useDataStore.getState().datasets[0].data![1][j];
if (!st.undoDataset("demo")) throw Error("Undo did not apply");
const restored=useDataStore.getState().datasets[0];
const timing = [10000,50000,150000].map(n=>{
  const table=[["score"],...Array.from({length:n},(_,i)=>[String(i)])];
  for (let warmup=0;warmup<3;warmup++) computeProfile(table);
  const ms=Array.from({length:9},()=>{const t=performance.now();computeProfile(table);return performance.now()-t;}).sort((a,b)=>a-b);
  return {n, medianMs:ms[4], minMs:ms[0], maxMs:ms[8]};
});
const sanitized = (table:string[][], columns:string[]) => table.map(r=>columns.map(c=>r[table[0].indexOf(c)]));
fs.writeFileSync(out,JSON.stringify({inputN:rows.length-1, missing:Object.fromEntries(items.map(c=>[c,masked.slice(1).filter(r=>r[cols.indexOf(c)]==="").length])), yearValues:groups, masked:sanitized(masked,[...items,"gpa_tu_bao_cao"]), scored:sanitized(scored,["gpa_tu_bao_cao","DIEM_TS","DIEM_NT"]), a:a.statistics,b:b.statistics,pca,agg,history:{before,changed,restored:restored.data![1][j],events:restored.audit?.entries?.map(e=>({kind:e.kind,action:e.action,columns:e.columns,related:e.kind==="undo"&&Boolean(e.originalChangeId)}))},timing}, null, 2));
